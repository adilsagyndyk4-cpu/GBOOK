<?php
/* =========================================================
   Задание 2. Упражнение 2: Создание файла журнала
   Формат записи: timestamp|запрошенная страница|реферер
   Одна строка - один путь.
   ========================================================= */

// Текущая временная метка
$dt = time();

// Запрошенный адрес
$page = $_SERVER['REQUEST_URI'] ?? '';

// Откуда пришёл пользователь
$ref = $_SERVER['HTTP_REFERER'] ?? '';

// Строка журнала с уникальным разделителем значений
$path = $dt . '|' . $page . '|' . $ref . PHP_EOL;

// Папка журнала: <корень сайта>/log
$logDir = __DIR__ . '/../log';

if (!is_dir($logDir)) {
    mkdir($logDir, 0777, true);
}

// Дописываем строку в конец файла (имя файла - в константе PATH_LOG)
file_put_contents($logDir . '/' . PATH_LOG, $path, FILE_APPEND | LOCK_EX);
